    private void PositionMenu()
    {
        if (Parent == null)
            return;

        var parentSize = Parent.Size;
        if (parentSize.X <= 2 || parentSize.Y <= 2)
            return;

        MenuFrame.Measure(parentSize);
        var size = MenuFrame.DesiredSize;

        var anchorX = _anchorControl?.GlobalPosition.X + _anchorControl?.Width ?? 410f;
        var anchorCenterY = _anchorControl != null
            ? _anchorControl.GlobalPosition.Y + _anchorControl.Height / 2f
            : parentSize.Y / 2f;

        var left = anchorX + 16f;
        var top = anchorCenterY - size.Y / 2f;

        left = Math.Clamp(left, 14f, Math.Max(14f, parentSize.X - size.X - 14f));
        top = Math.Clamp(top, 14f, Math.Max(14f, parentSize.Y - size.Y - 14f));

        LayoutContainer.SetMarginLeft(MenuFrame, left);
        LayoutContainer.SetMarginTop(MenuFrame, top);
    }

