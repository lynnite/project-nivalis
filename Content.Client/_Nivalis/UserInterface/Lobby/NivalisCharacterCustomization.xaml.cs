    private void UpdateSkinControls()
    {
        if (Profile == null || _skinSlider == null || _rgbSkinContainer == null || _rgbSkinSelector == null)
            return;

        var skin = _proto.Index<SpeciesPrototype>(Profile.Species).SkinColoration;
        var strategy = _proto.Index(skin).Strategy;

        switch (strategy.InputType)
        {
            case SkinColorationStrategyInput.Unary:
                _skinSlider.Visible = true;
                _rgbSkinContainer.Visible = false;
                _skinSlider.Value = strategy.ToUnary(Profile.Appearance.SkinColor);
                break;
            case SkinColorationStrategyInput.Color:
                _skinSlider.Visible = false;
                _rgbSkinContainer.Visible = true;
                _rgbSkinSelector.Color = strategy.ClosestSkinColor(Profile.Appearance.SkinColor);
                break;
        }
    }

    private void UpdateEyePicker()
    {
        if (Profile == null || _eyeColorPicker == null)
            return;
        _markingsModel.SetOrganEyeColor(Profile.Appearance.EyeColor);
        _eyeColorPicker.Color = Profile.Appearance.EyeColor;
    }

    private void OnSkinColorChanged()
    {
        if (Profile == null)
            return;

        var skin = _proto.Index<SpeciesPrototype>(Profile.Species).SkinColoration;
        var strategy = _proto.Index(skin).Strategy;

        Color color;
        switch (strategy.InputType)
        {
            case SkinColorationStrategyInput.Unary:
                color = strategy.FromUnary(_skinSlider!.Value);
                _markingsModel.SetOrganSkinColor(color);
                Profile = Profile.WithCharacterAppearance(Profile.Appearance.WithSkinColor(color));
                break;
            case SkinColorationStrategyInput.Color:
                color = strategy.ClosestSkinColor(_rgbSkinSelector!.Color);
                _markingsModel.SetOrganSkinColor(color);
                Profile = Profile.WithCharacterAppearance(Profile.Appearance.WithSkinColor(color));
                break;
            default:
                return;
        }

        PreviewSprite.ReloadProfilePreview(Profile);
    }

