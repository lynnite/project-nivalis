    }

    private static string HumanizeId(string id)
    {
        var builder = new System.Text.StringBuilder(id.Length + 8);
        for (var i = 0; i < id.Length; i++)
        {
            var c = id[i];
            if (c is '_' or '-')
            {
                builder.Append(' ');
                continue;
            }

            if (i > 0 && char.IsUpper(c) && !char.IsUpper(id[i - 1]))
                builder.Append(' ');

            builder.Append(c);
        }

        return builder.ToString();
    }

