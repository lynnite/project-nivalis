    private void BuildMarkingCategory(HumanoidVisualLayers layer)
    {
        var organs = _marking.GetMarkingData(Profile?.Species ?? ForcedSpecies);
        ProtoId<OrganCategoryPrototype>? matchedOrgan = null;
        foreach (var (organ, data) in organs)
        {
            if (data.Layers.Contains(layer))
            {
                matchedOrgan = organ;
                break;
            }
        }

        if (matchedOrgan == null)
        {
            ContentBody.AddChild(MakeLabel(Loc.GetString("nivalis-customization-no-species-options"), _displaySmall, "#8FA3B8"));
            return;
        }

        var organId = matchedOrgan.Value;
        var organData = organs[organId];

        if (!_markingsModel.OrganProfileData.TryGetValue(organId, out var profileData))
        {
            ContentBody.AddChild(MakeLabel("NO ORGAN DATA AVAILABLE.", _displaySmall, "#8FA3B8"));
            return;
        }

        var allMarkings = _markingsModel.EnforceGroupAndSexRestrictions
            ? _marking.MarkingsByLayerAndGroupAndSex(layer, organData.Group, profileData.Sex)
            : _marking.MarkingsByLayer(layer);

        _activeOrgan = organId;
        _activeLayer = layer;
        _hasActiveLayer = true;

        if (allMarkings.Count == 0)
        {
            ContentBody.AddChild(MakeLabel(Loc.GetString("nivalis-customization-no-options"), _displaySmall, "#8FA3B8"));
            return;
        }

        var grid = new GridContainer { Columns = 4, HorizontalExpand = true };
        ContentBody.AddChild(grid);

        var noneButton = new SlantedButton
        {
            Text = Loc.GetString("nivalis-customization-none"),
            MinSize = new Vector2(96, 96),
            MaxSize = new Vector2(96, 96),
            HorizontalAlignment = Control.HAlignment.Center,
            VerticalAlignment = Control.VAlignment.Center,
        };
        var noneStyle = new ScrollingScanlineStyleBox
        {
            Texture = _scanlineTexture,
            BackgroundColor = Color.FromHex("#101d33"),
            BorderColor = Color.FromHex("#3E7FB0").WithAlpha(0.6f),
            BorderThickness = 1.5f,
            InwardLean = 0.05f,
            SlantPixels = NavSlantPixels,
        };
        noneButton.StyleBoxOverride = noneStyle;
        noneButton.OnMouseEntered += _ => noneButton.VisualScale = new Vector2(1.005f, 1.005f);
        noneButton.OnMouseExited += _ => noneButton.VisualScale = Vector2.One;
        noneButton.OnPressed += _ => ClearCurrentLayer();
        grid.AddChild(noneButton);
        _noneTile = noneButton;

        foreach (var marking in allMarkings.Values.OrderBy(m => MarkingName(m.ID)))
        {
            var tile = MakeMarkingTile(organId, layer, marking);
            grid.AddChild(tile);
        }

        _markingColorContainer = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 6,
            Margin = new Thickness(0, 8, 0, 0),
        };
        ContentBody.AddChild(_markingColorContainer);

        UpdateMarkingTilesVisual(0.016f);
        RefreshMarkingColors();
    }

    private void ClearMarkingLayer(HumanoidVisualLayers layer)
    {
        var organs = _marking.GetMarkingData(Profile?.Species ?? ForcedSpecies);
        foreach (var (organ, data) in organs)
        {
            if (!data.Layers.Contains(layer))
                continue;

            var selected = _markingsModel.SelectedMarkings(organ, layer);
            if (selected == null)
                continue;

            var previousLimits = _markingsModel.EnforceLimits;
            _markingsModel.EnforceLimits = false;
            foreach (var marking in selected.ToList())
                _markingsModel.TryDeselectMarking(organ, layer, marking.MarkingId);
            _markingsModel.EnforceLimits = previousLimits;
        }
    }

    private void ClearCurrentLayer()
    {
        if (!_hasActiveLayer)
            return;

        var current = _markingsModel.SelectedMarkings(_activeOrgan, _activeLayer);
        if (current == null)
            return;

        var previousLimits = _markingsModel.EnforceLimits;
        _markingsModel.EnforceLimits = false;
        foreach (var marking in current.ToList())
            _markingsModel.TryDeselectMarking(_activeOrgan, _activeLayer, marking.MarkingId);
        _markingsModel.EnforceLimits = previousLimits;

        RefreshMarkingColors();
    }

    private Button MakeMarkingTile(ProtoId<OrganCategoryPrototype> organ, HumanoidVisualLayers layer, MarkingPrototype prototype)
    {
        var tile = new SlantedButton
        {
            MinSize = new Vector2(96, 96),
            MaxSize = new Vector2(96, 96),
            HorizontalAlignment = Control.HAlignment.Center,
            VerticalAlignment = Control.VAlignment.Center,
            ToolTip = MarkingName(prototype.ID),
        };

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalExpand = true,
        };

        var texRect = new LayeredTextureRect
        {
            TextureScale = new Vector2(2, 2),
            HorizontalAlignment = Control.HAlignment.Center,
            VerticalAlignment = Control.VAlignment.Center,
            HorizontalExpand = true,
            VerticalExpand = true,
        };
        texRect.Textures = prototype.Sprites.Select(s => Sprite.Frame0(s)).ToList();
        content.AddChild(texRect);
        tile.AddChild(content);

        var normal = new ScrollingScanlineStyleBox
        {
            Texture = _scanlineTexture,
            BackgroundColor = Color.FromHex("#20375c"),
            BorderColor = Color.FromHex("#5f93c8").WithAlpha(0.7f),
            BorderThickness = 1.5f,
            InwardLean = 0.05f,
        };
        var selected = new ScrollingScanlineStyleBox
        {
            Texture = _scanlineTexture,
            BackgroundColor = Color.FromHex("#c3dbf2"),
            BorderColor = Color.FromHex("#eaf5ff"),
            BorderThickness = 3f,
            InwardLean = 0.05f,
        };

        _markingStyle[tile] = normal;
        _markingSelectedStyle[tile] = selected;
        tile.StyleBoxOverride = normal;

        _markingTiles.Add(tile);
        _markingTileData[tile] = new MarkingTileData
        {
            Prototype = prototype,
            Organ = organ,
            Layer = layer,
        };
        _markingEngaged[tile] = 0f;

        tile.OnPressed += _ => OnMarkingTilePressed(tile);
        tile.OnMouseEntered += _ => _hoveredMarkingTile = tile;
        tile.OnMouseExited += _ =>
        {
            if (ReferenceEquals(_hoveredMarkingTile, tile))
                _hoveredMarkingTile = null;
        };

        RefreshMarkingTileSelection(tile);
        return tile;
    }

    private void OnMarkingTilePressed(Button tile)
    {
        if (!_markingTileData.TryGetValue(tile, out var data))
            return;

        if (_markingsModel.IsMarkingSelected(data.Organ, data.Layer, data.Prototype.ID))
            _markingsModel.TryDeselectMarking(data.Organ, data.Layer, data.Prototype.ID);
        else
            _markingsModel.TrySelectMarking(data.Organ, data.Layer, data.Prototype.ID);

        RefreshMarkingTileSelection(tile);
        RefreshMarkingColors();
    }

    private void RefreshMarkingTileSelection(Button tile)
    {
        if (!_markingTileData.TryGetValue(tile, out var data))
            return;

        var isSelected = _markingsModel.IsMarkingSelected(data.Organ, data.Layer, data.Prototype.ID);
        tile.StyleBoxOverride = isSelected && _markingSelectedStyle.TryGetValue(tile, out var sel)
            ? sel
            : _markingStyle[tile];
    }

    private void RefreshMarkingColors()
    {
        if (_markingColorContainer == null || !_hasActiveLayer)
            return;

        _markingColorContainer.RemoveAllChildren();

        var selected = _markingsModel.SelectedMarkings(_activeOrgan, _activeLayer);

        if (_noneTile != null)
        {
            if (selected == null || selected.Count == 0)
            {
                _noneTile.StyleBoxOverride = new ScrollingScanlineStyleBox
                {
                    Texture = _scanlineTexture,
                    BackgroundColor = Color.FromHex("#c3dbf2"),
                    BorderColor = Color.FromHex("#eaf5ff"),
                    BorderThickness = 3f,
                    InwardLean = 0.05f,
                };
            }
            else
            {
                _noneTile.StyleBoxOverride = new ScrollingScanlineStyleBox
                {
                    Texture = _scanlineTexture,
                    BackgroundColor = Color.FromHex("#101d33"),
                    BorderColor = Color.FromHex("#3E7FB0").WithAlpha(0.6f),
                    BorderThickness = 1.5f,
                    InwardLean = 0.05f,
                };
            }
        }

        if (selected == null || selected.Count == 0)
            return;

        var marking = selected[^1];
        if (!_proto.TryIndex(marking.MarkingId, out MarkingPrototype? markingProto))
            return;

        if (!_markingsModel.IsMarkingColorCustomizable(_activeOrgan, _activeLayer, marking.MarkingId))
            return;

        _markingColorContainer.AddChild(MakeLabel("COLOR", _displayRegular, "#58C6E8"));

        for (var i = 0; i < markingProto.Sprites.Count && i < marking.MarkingColors.Count; i++)
        {
            var container = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
            };

            var label = markingProto.Sprites[i] switch
            {
                SpriteSpecifier.Rsi rsi => MarkingLayerName(markingProto.ID, rsi.RsiState),
                SpriteSpecifier.Texture texture => MarkingLayerName(markingProto.ID, texture.TexturePath.Filename),
                _ => $"Layer {i + 1}",
            };

            var selector = new NivalisColorSliders
            {
                ScanlineTexture = _scanlineTexture,
                Color = marking.MarkingColors[i],
            };

            var colorIndex = i;
            selector.OnColorChanged += _ =>
            {
                _markingsModel.TrySetMarkingColor(_activeOrgan, _activeLayer, marking.MarkingId, colorIndex, selector.Color);
            };

            container.AddChild(new Label { Text = label, FontOverride = _displaySmall, FontColorOverride = Color.FromHex("#8FA3B8") });
            container.AddChild(selector);
            _markingColorContainer.AddChild(container);
        }
    }

    private void OnMarkingsReset()
    {
        foreach (var tile in _markingTiles)
            RefreshMarkingTileSelection(tile);

        RefreshMarkingColors();
    }

    private void OnMarkingsChanged(ProtoId<OrganCategoryPrototype> organ, HumanoidVisualLayers layer)
    {
        if (!_hasActiveLayer || organ != _activeOrgan || layer != _activeLayer)
            return;

        foreach (var tile in _markingTiles)
            RefreshMarkingTileSelection(tile);

        if (Profile != null)
        {
            Profile = Profile.WithCharacterAppearance(Profile.Appearance.WithMarkings(_markingsModel.Markings));
            PreviewSprite.ReloadProfilePreview(Profile);
        }
    }

    private void UpdateMarkingTilesVisual(float delta)
    {
        if (_markingTiles.Count == 0)
            return;

        var ease = 1f - MathF.Exp(-14f * Math.Max(delta, 0.016f));

        foreach (var tile in _markingTiles)
        {
            if (!_markingTileData.TryGetValue(tile, out var data))
                continue;

            var engagedNow = ReferenceEquals(tile, _hoveredMarkingTile)
                || _markingsModel.IsMarkingSelected(data.Organ, data.Layer, data.Prototype.ID);

            _markingEngaged.TryGetValue(tile, out var cur);
            var targetE = engagedNow ? 1f : 0f;
            var e = cur + (targetE - cur) * ease;
            _markingEngaged[tile] = e;

            var bright = 0.92f + 0.12f * e;
            tile.Modulate = new Color(bright, bright, bright, 1f);

            var scale = 1f + 0.005f * e;
            if (tile is SlantedButton slanted)
                slanted.VisualScale = new Vector2(scale, scale);
        }
    }

