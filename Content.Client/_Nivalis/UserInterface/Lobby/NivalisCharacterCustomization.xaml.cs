    private static Texture GenerateFadeTexture(bool topToBottom)
    {
        const int width = 8;
        const int height = 32;

        using var image = new SixLabors.ImageSharp.Image<SixLabors.ImageSharp.PixelFormats.Rgba32>(
            SixLabors.ImageSharp.Configuration.Default, width, height);
        for (var y = 0; y < height; y++)
        {
            var t = y / (float)(height - 1);
            var alpha = (1f - t) * (1f - t);
            var a = (byte)(alpha * 235);
            var pixel = new SixLabors.ImageSharp.PixelFormats.Rgba32(1, 3, 8, a);
            var row = topToBottom ? y : height - 1 - y;
            for (var x = 0; x < width; x++)
                image[x, row] = pixel;
        }

        return Texture.LoadFromImage(image, "NivalisScrollFade");
    }

    private void UpdateScrollFades()
    {
        var viewport = ContentScroll.Height;
        var content = ContentBody.DesiredSize.Y;
        var max = content - viewport;
        if (max <= 1f)
        {
            FadeTop.Visible = false;
            FadeBottom.Visible = false;
            return;
        }

        var scroll = ContentScroll.VScroll;
        const float epsilon = 1.5f;
        FadeTop.Visible = scroll > epsilon;
        FadeBottom.Visible = scroll < max - epsilon;
    }

    private void UpdateCategoryAnimations(float frameTime)
    {
        foreach (var style in _catStyle.Values)
        {
            style.ScrollOffset += frameTime * IdleScrollSpeed;
        }

        foreach (var (button, style) in _catStyle)
        {
            var amountTarget = _catHover[button] ? 1f : 0f;
            var amount = _catHoverAmount[button];
            var lerp = 1f - MathF.Exp(-HoverLerpSpeed * frameTime);
            amount += (amountTarget - amount) * lerp;
            _catHoverAmount[button] = amount;

            var speed = _catHover[button] ? HoverScrollSpeed : IdleScrollSpeed;
            style.ScrollOffset += frameTime * (speed - IdleScrollSpeed);

            if (button is SlantedButton slanted)
                slanted.VisualScale = new Vector2(1f + 0.005f * amount, 1f + 0.005f * amount);
        }

        foreach (var style in _markingStyle.Values)
            style.ScrollOffset += frameTime * IdleScrollSpeed;
        foreach (var style in _markingSelectedStyle.Values)
            style.ScrollOffset += frameTime * IdleScrollSpeed;
        _panelStyle.ScrollOffset += frameTime * IdleScrollSpeed;
        _contentStyle.ScrollOffset += frameTime * IdleScrollSpeed;
    }

