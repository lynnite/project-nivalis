    public void SetProfile(HumanoidCharacterProfile? profile, int? slot)
    {
        Profile = profile?.Clone();
        CharacterSlot = slot;

        if (Profile == null)
        {
            Profile = HumanoidCharacterProfile.DefaultWithSpecies(ForcedSpecies);
        }
        else
        {
            Profile = Profile.WithSpecies(ForcedSpecies);
        }

        AgentNameLabel.Text = Profile.Name;

        _markingsModel.OrganData = _marking.GetMarkingData(Profile.Species);
        _markingsModel.OrganProfileData = _marking.GetProfileData(
            Profile.Species,
            Profile.Sex,
            Profile.Appearance.SkinColor,
            Profile.Appearance.EyeColor);
        _markingsModel.Markings = Profile.Appearance.Markings;

        _markingsModel.ValidateMarkings();

        ClearMarkingLayer(HumanoidVisualLayers.Tail);
        ClearMarkingLayer(HumanoidVisualLayers.HeadTop);

        Profile = Profile.WithCharacterAppearance(Profile.Appearance.WithMarkings(_markingsModel.Markings));

        SetPreviewForCategory(_activeCategoryId);
        ReloadPreview();
        BuildCategoryContent();
    }

    private void SetPreviewForCategory(string category)
    {
        _previewRotation = category == "tail" ? Direction.East : Direction.North;
        SetPreviewRotation(_previewRotation);
    }

    private void ReloadPreview()
    {
        if (Profile == null)
        {
            PreviewSprite.ClearPreview();
            return;
        }

        PreviewSprite.LoadPreview(Profile);
        AgentNameLabel.Text = Profile.Name;
        SetPreviewRotation(_previewRotation);
    }

    private void SetPreviewRotation(Direction direction)
    {
        PreviewSprite.OverrideDirection = (Direction)((int)direction % 4 * 2);
    }

    private void Save()
    {
        if (Profile == null || CharacterSlot == null)
        {
            Closed?.Invoke();
            return;
        }

        if (_preferences.Preferences?.SelectedCharacterIndex != CharacterSlot)
        {
            Closed?.Invoke();
            return;
        }

        _preferences.UpdateCharacter(Profile, CharacterSlot.Value);
        Closed?.Invoke();
    }

