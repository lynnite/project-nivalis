    private void RefreshSex()
    {
        if (_sexButton == null || Profile == null)
            return;

        _sexButton.Clear();
        var sexes = new List<Sex>();
        if (_proto.TryIndex(Profile.Species, out SpeciesPrototype? speciesProto))
            sexes.AddRange(speciesProto.Sexes);
        else
            sexes.Add(Sex.Unsexed);

        foreach (var sex in sexes)
            _sexButton.AddItem(Loc.GetString($"humanoid-profile-editor-sex-{sex.ToString().ToLower()}-text"), (int)sex);

        if (sexes.Contains(Profile.Sex))
            _sexButton.SelectId((int)Profile.Sex);
        else if (sexes.Count > 0)
            _sexButton.SelectId((int)sexes[0]);
    }

