    private readonly Dictionary<Button, int> _traitIndex = new();

    private void BuildTraitsMenu()
    {
        ArcContainer.RemoveAllChildren();
        _traitPickButtons.Clear();
        _traitStyle.Clear();
        _traitIndex.Clear();

        var traits = _proto.EnumeratePrototypes<NivalisTraitPrototype>().ToList();
        for (var i = 0; i < traits.Count; i++)
        {
            var trait = traits[i];
            var name = Loc.GetString(trait.Name);
            var desc = Loc.GetString(trait.Description);

            var pickButton = new Button
            {
                HorizontalAlignment = HAlignment.Center,
                MinSize = new Vector2(320, 70),
            };

            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
            };
            var header = new Label
            {
                Text = name,
                FontColorOverride = Color.FromHex("#CFE3FF"),
                HorizontalExpand = true,
                Margin = new Thickness(12, 5, 12, 1),
            };
            var descLabel = new Label
            {
                Text = desc,
                FontColorOverride = Color.FromHex("#8FA3B8"),
                FontOverride = _displaySmall,
                HorizontalExpand = true,
                HorizontalAlignment = HAlignment.Left,
                Margin = new Thickness(12, 0, 12, 6),
            };
            content.AddChild(header);
            content.AddChild(descLabel);
            pickButton.AddChild(content);

            var traitId = new ProtoId<NivalisTraitPrototype>(trait.ID);
            pickButton.OnPressed += _ => OnTraitToggled(traitId);
            _traitPickButtons[pickButton] = traitId;
            _traitIndex[pickButton] = i;

            var scanlineBox = new ScrollingScanlineStyleBox
            {
                Texture = _scanlineTexture,
            };
            _traitStyle[pickButton] = scanlineBox;
            pickButton.StyleBoxOverride = scanlineBox;

            ArcContainer.AddChild(pickButton);
        }

        RefreshTraitHighlights();
        RefreshTraitsCount();
    }

    private void OnTraitToggled(ProtoId<NivalisTraitPrototype> traitId)
    {
        if (_selectedTraits.Contains(traitId))
        {
            _selectedTraits.Remove(traitId);
        }
        else if (_selectedTraits.Count < MaxTraits)
        {
            _selectedTraits.Add(traitId);
        }

        RefreshTraitHighlights();
        RefreshTraitsCount();
        TraitsChanged?.Invoke();
    }

    private void RefreshTraitHighlights()
    {
        foreach (var (button, traitId) in _traitPickButtons)
        {
            var selected = _selectedTraits.Contains(traitId);
            if (selected)
                button.StyleBoxOverride = _traitSelectedBox;
            else if (_traitStyle.TryGetValue(button, out var scanline))
                button.StyleBoxOverride = scanline;
        }
    }

    private void RefreshTraitsCount()
    {
        TraitsCountValue.Text = $"SELECTED: {_selectedTraits.Count}/{MaxTraits}";
    }

    private void UpdateCarouselEffects()
    {
        if (_traitPickButtons.Count == 0)
            return;

        var viewport = Math.Max(TraitsScroll.Size.Y, 1f);
        var scroll = TraitsScroll.VScroll;
        var baseH = 70f;
        var sep = 14f;
        var stride = baseH + sep;
        var count = _traitPickButtons.Count;

        var available = Math.Max(TraitsScroll.Size.X - 16f, 1f);
        var contentHeight = (count - 1) * stride + baseH;
        var scrollRange = Math.Max(contentHeight - viewport, 1f);
        var frac = Math.Clamp(scroll / scrollRange, 0f, 1f);

        var firstCenter = baseH / 2f;
        var focusCenter = firstCenter + frac * ((count - 1) * stride);
        var halfSpan = Math.Max(viewport * 0.5f, 1f);

        foreach (var (button, _) in _traitPickButtons)
        {
            var idx = _traitIndex[button];
            var rowCenter = idx * stride + baseH / 2f;
            var t = Math.Clamp(Math.Abs(rowCenter - focusCenter) / halfSpan, 0f, 1f);
            t = t * t * (3f - 2f * t);

            var bright = 1.12f - t * 0.45f;
            button.Modulate = new Color(bright, bright, bright, 1f);

            var height = baseH * (1f + 0.2f * (1f - t));
            var popUp = (1f - t) * 3f;
            button.MinSize = new Vector2(available, height);
            button.Margin = new Thickness(0, -popUp, 0, popUp);
        }
    }

    private void DimNavButtons(bool dimmed)
    {
        var dim = dimmed ? Color.FromHex("#33333a") : Color.White;
        foreach (var button in _navStyle.Keys)
        {
            if (button == TraitsButton)
                continue;

            _navStyle[button].Modulate = dim;
        }
    }

    private void OnNavHover(Button button, bool hovering)
    {
        _navHover[button] = hovering;
    }

    private void UpdateNavAnimations(float frameTime)
    {
        var hoveredIndex = -1;
        foreach (var kvp in _navHover)
        {
            if (kvp.Value)
            {
                hoveredIndex = _navIndex[kvp.Key];
                break;
            }
        }

        foreach (var button in _navButtons)
        {
            var baseSize = _navBaseSize[button];
            var idx = _navIndex[button];
            var isHovered = idx == hoveredIndex;
            var isNeighbor = hoveredIndex >= 0 && Math.Abs(idx - hoveredIndex) == 1;

            if (isHovered)
            {
                _navTargetSize[button] = new Vector2(baseSize.X * HoverScale, baseSize.Y * HoverScale);
            }
            else if (isNeighbor)
            {
                _navTargetSize[button] = new Vector2(baseSize.X, baseSize.Y * NeighborShrinkScale);
            }
            else
            {
                _navTargetSize[button] = baseSize;
            }
        }

        foreach (var (button, style) in _navStyle)
        {
            var current = _navCurrentSize[button];
            var target = _navTargetSize[button];
            var hoverAmount = _navHoverAmount[button];

            var amountTarget = _navHover[button] ? 1f : 0f;
            var lerp = 1f - MathF.Exp(-HoverLerpSpeed * frameTime);
            var amount = hoverAmount + (amountTarget - hoverAmount) * lerp;
            _navHoverAmount[button] = amount;

            var newSize = new Vector2(
                current.X + (target.X - current.X) * lerp,
                current.Y + (target.Y - current.Y) * lerp);
            _navCurrentSize[button] = newSize;
            button.MinSize = newSize;

            var speed = _navHover[button] ? HoverScrollSpeed : IdleScrollSpeed;
            style.ScrollOffset += frameTime * speed;

            var bright = 0.82f + 0.15f * amount;
            style.Modulate = new Color(bright, bright, bright, 1f);
        }

        foreach (var style in _traitStyle.Values)
        {
            style.ScrollOffset += frameTime * IdleScrollSpeed;
        }

        if (_traitsPanelOpen)
        {
            PositionTraitsPanel();
            DimNavButtons(true);
        }
    }

    private void OnReadyPressed(BaseButton.ButtonEventArgs args)
    {
        var ticker = _entityManager.System<ClientGameTicker>();
        if (ticker.IsGameStarted)
        {
            _netManager.SendSystemNetworkMessage(new NivalisJoinGameMessage());
            return;
        }

        var newState = !ticker.AreWeReady;
        _consoleHost.ExecuteCommand($"toggleready {newState}");
        SetReadyState(newState);
    }

    public void SetReadyState(bool ready)
    {
        _areWeReady = ready;
        var ticker = _entityManager.System<ClientGameTicker>();
        ReadyButton.Text = ticker.IsGameStarted
            ? "JOIN GAME"
            : ready ? "READY" : "NOT READY";
    }

    public void LoadCharacterPreview()
    {
        // Can't spawn the character dummy until the entity manager is fully initialised
        // (its MetaQuery/entity store is only set up during EntityManager.Initialize).
        // The LobbyUIController reloads the preview whenever the LobbyState is entered,
        // so it's safe to defer if preferences arrive before we're ready.
        if (_entityManager is EntityManager { Initialized: false })
            return;

        if (_preferences.Preferences?.SelectedCharacter is not HumanoidCharacterProfile humanoid)
        {
            AgentPreview.ClearPreview();
            AgentNameLabel.Text = "UNKNOWN";
            return;
        }

        // The character preview can't spawn a humanoid for a species that lacks a doll
        // prototype, which would otherwise throw at runtime. Fall back to the default
        // species in that case so the lobby always has a working preview.
        if (!_proto.HasIndex<SpeciesPrototype>(humanoid.Species)
            || _proto.Index<SpeciesPrototype>(humanoid.Species).DollPrototype == default)
        {
            humanoid = new HumanoidCharacterProfile(humanoid)
            {
                Species = HumanoidCharacterProfile.DefaultSpecies,
            };
        }

        AgentPreview.LoadPreview(humanoid);
        AgentNameLabel.Text = humanoid.Name;

        if (AgentTitleLabel.FontOverride == null)
            AgentTitleLabel.FontOverride = _displayRegular;
        AgentNameLabel.FontOverride = _displayRegular;
    }

    public void UpdatePlayerProgression(int level, int odens, int bonds, int tier)
    {
        LevelValue.Text = level.ToString();
        OdensValue.Text = odens.ToString();
        BondsValue.Text = bonds.ToString();
        TierValue.Text = tier.ToString();
    }

    public void UpdateMatchStats(int readyCount, int activeCount, TimeSpan respawnRemaining, int cycle)
    {
        ReadyCountValue.Text = readyCount.ToString();
        ActiveCountValue.Text = activeCount.ToString();

        RespawnTimerValue.Text = respawnRemaining <= TimeSpan.Zero
            ? "0:00"
            : $"{(int) Math.Ceiling(respawnRemaining.TotalSeconds) / 60}:{(int) Math.Ceiling(respawnRemaining.TotalSeconds) % 60:00}";

        CycleValue.Text = cycle.ToString();
    }

    public void UpdateDiagnostics(float frameTime)
    {
        var ticker = _entityManager.System<ClientGameTicker>();
        if (ticker.AreWeReady != _areWeReady)
            SetReadyState(ticker.AreWeReady);
        else if (ticker.IsGameStarted && ReadyButton.Text != "JOIN GAME")
            SetReadyState(_areWeReady);

        UpdateNavAnimations(frameTime);
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
    }
