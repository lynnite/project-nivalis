    private void BuildTraitsMenu()
    {
        ArcContainer.RemoveAllChildren();
        _traitPickButtons.Clear();
        _traitStyle.Clear();
        _traitIndex.Clear();

        var traits = _proto.EnumeratePrototypes<NivalisTraitPrototype>().ToList();
        for (var i = 0; i < traits.Count; i++)
        {
            var trait = traits[i];
            var name = Loc.GetString(trait.Name);
            var desc = Loc.GetString(trait.Description);

            var pickButton = new Button
            {
                HorizontalAlignment = HAlignment.Right,
                MinSize = new Vector2(320, 70),
                MaxSize = new Vector2(320, 70),
            };

            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
            };
            var header = new Label
            {
                Text = name,
                FontColorOverride = Color.FromHex("#CFE3FF"),
                HorizontalExpand = true,
                Margin = new Thickness(12, 5, 12, 1),
            };
            var descLabel = new Label
            {
                Text = desc,
                FontColorOverride = Color.FromHex("#8FA3B8"),
                FontOverride = _displayTiny,
                HorizontalExpand = true,
                Margin = new Thickness(12, 0, 12, 6),
            };
            content.AddChild(header);
            content.AddChild(descLabel);
            pickButton.AddChild(content);

            var traitId = new ProtoId<NivalisTraitPrototype>(trait.ID);
            pickButton.OnPressed += _ => OnTraitToggled(traitId);
            _traitPickButtons[pickButton] = traitId;
            _traitIndex[pickButton] = i;

            var scanlineBox = new ScrollingScanlineStyleBox
            {
                Texture = _scanlineTexture,
                InwardLean = -0.08f,
                FadeRight = 0.55f,
            };
            _traitStyle[pickButton] = scanlineBox;
            pickButton.StyleBoxOverride = scanlineBox;

            ArcContainer.AddChild(pickButton);
        }

        RefreshTraitHighlights();
        RefreshTraitsCount();
    }

    private void OnTraitToggled(ProtoId<NivalisTraitPrototype> traitId)
    {
        if (_selectedTraits.Contains(traitId))
        {
            _selectedTraits.Remove(traitId);
        }
        else if (_selectedTraits.Count < MaxTraits)
        {
            _selectedTraits.Add(traitId);
        }

        RefreshTraitHighlights();
        RefreshTraitsCount();
        TraitsChanged?.Invoke();
    }

    private void RefreshTraitHighlights()
    {
        foreach (var (button, traitId) in _traitPickButtons)
        {
            var selected = _selectedTraits.Contains(traitId);
            if (selected)
                button.StyleBoxOverride = _traitSelectedBox;
            else if (_traitStyle.TryGetValue(button, out var scanline))
                button.StyleBoxOverride = scanline;
        }
    }

