    private void PositionTraitsPanel()
    {
        var parent = TraitsPanel.Parent;
        if (parent == null)
            return;

        TraitsPanel.PanelOverride = _traitsPanelBackground;

        UpdateCarouselEffects();

        var parentSize = parent.Size;
        if (parentSize.X <= 1 || parentSize.Y <= 1)
            return;

        TraitsPanel.Measure(parentSize);
        var height = Math.Clamp(TraitsPanel.DesiredSize.Y, TraitsPanel.MinHeight, TraitsPanel.MinHeight);
        if (height <= 0)
            height = 520;
        height = Math.Clamp(height, 0, parentSize.Y - 40);

        var traitsCenterY = TraitsButton.GlobalPosition.Y + TraitsButton.Height / 2f;
        var left = TraitsButton.GlobalPosition.X + TraitsButton.Width + 14;
        var top = traitsCenterY - height / 2f;

        var width = (parentSize.X - left - 14) / 2;
        width = Math.Max(width, TraitsPanel.MinWidth);

        left = Math.Clamp(left, 14, parentSize.X - width - 14);
        top = Math.Clamp(top, 14, parentSize.Y - height - 14);

        LayoutContainer.SetAnchorPreset(TraitsPanel, LayoutContainer.LayoutPreset.TopLeft);
        LayoutContainer.SetMarginLeft(TraitsPanel, left);
        LayoutContainer.SetMarginTop(TraitsPanel, top);
        LayoutContainer.SetMarginRight(TraitsPanel, left + width);
        LayoutContainer.SetMarginBottom(TraitsPanel, top + height);
    }

