    public NivalisLobbyControl()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        _displayBold = _resourceCache.GetFont("/Fonts/Orbitron/Orbitron-Bold.ttf", 28);
        _displayRegular = _resourceCache.GetFont("/Fonts/Orbitron/Orbitron-Regular.ttf", 15);
        _displaySmall = _resourceCache.GetFont("/Fonts/Orbitron/Orbitron-Regular.ttf", 11);
        LayoutContainer.SetAnchorPreset(BackgroundViewport, LayoutContainer.LayoutPreset.Wide);
        LayoutContainer.SetAnchorAndMarginPreset(Header, LayoutContainer.LayoutPreset.TopWide, margin: 20);
        LayoutContainer.SetAnchorAndMarginPreset(ChatPanel, LayoutContainer.LayoutPreset.RightWide, margin: 18);
        LayoutContainer.SetAnchorAndMarginPreset(CharacterViewport, LayoutContainer.LayoutPreset.Center);
        LayoutContainer.SetAnchorAndMarginPreset(Navigation, LayoutContainer.LayoutPreset.CenterLeft, margin: 30);
        LayoutContainer.SetAnchorAndMarginPreset(ProgressionBox, LayoutContainer.LayoutPreset.BottomLeft, margin: 24);

        _scanlineTexture = GenerateScanlines();

        BackgroundViewport.Texture = null;

        TitleLabel.FontOverride = _displayBold;
        TitleLabel.Margin = new Thickness(0, 0, 0, 4);
        foreach (var label in HeaderLabels())
            label.FontOverride = _displayRegular;

        ReadyButton.OnPressed += OnReadyPressed;
        LoadoutButton.OnPressed += _ => NavigationPressed?.Invoke("loadout");
        TraitsButton.OnPressed += OnTraitsPressed;
        ChallengesButton.OnPressed += _ => NavigationPressed?.Invoke("challenges");
        QuartermasterButton.OnPressed += _ => NavigationPressed?.Invoke("quartermaster");
        PatreonButton.OnPressed += _ => _uriOpener.OpenUri("https://www.patreon.com/cw/lynnite");
        SettingsButton.OnPressed += _ => NavigationPressed?.Invoke("settings");
        QuitButton.OnPressed += _ => _consoleHost.ExecuteCommand("disconnect");

        SetupNavButtons();
        BuildTraitsMenu();
        PositionTraitsPanel();

        TraitsChanged += OnTraitsChanged;
    }

    private void PositionTraitsPanel()
    {
        var parent = TraitsPanel.Parent;
        if (parent == null)
            return;

        TraitsPanel.PanelOverride = _traitsPanelBackground;

        UpdateCarouselEffects();

        var parentSize = parent.Size;
        if (parentSize.X <= 1 || parentSize.Y <= 1)
            return;

        TraitsPanel.Measure(parentSize);
        var height = Math.Clamp(TraitsPanel.DesiredSize.Y, TraitsPanel.MinHeight, TraitsPanel.MinHeight);
        if (height <= 0)
            height = 520;
        height = Math.Clamp(height, 0, parentSize.Y - 40);

        var traitsCenterY = TraitsButton.GlobalPosition.Y + TraitsButton.Height / 2f;
        var left = TraitsButton.GlobalPosition.X + TraitsButton.Width + 14;
        var top = traitsCenterY - height / 2f;

        var width = (parentSize.X - left - 14) / 2;
        width = Math.Max(width, TraitsPanel.MinWidth);

        left = Math.Clamp(left, 14, parentSize.X - width - 14);
        top = Math.Clamp(top, 14, parentSize.Y - height - 14);

        LayoutContainer.SetAnchorPreset(TraitsPanel, LayoutContainer.LayoutPreset.TopLeft);
        LayoutContainer.SetMarginLeft(TraitsPanel, left);
        LayoutContainer.SetMarginTop(TraitsPanel, top);
        LayoutContainer.SetMarginRight(TraitsPanel, left + width);
        LayoutContainer.SetMarginBottom(TraitsPanel, top + height);
    }

    private void OnTraitsChanged()
    {
        _netManager.SendSystemNetworkMessage(new NivalisTraitsSelectedMessage
        {
            Traits = new List<ProtoId<NivalisTraitPrototype>>(_selectedTraits),
        });
    }

